# Создаем главное окно приложения
window = tk.Tk()

# Задаем начальные размеры окна в пикселях: ширина 576, высота 360
window.geometry('576x360')

# Загружаем картинку из файла в специальный объект PhotoImage, понятный для tkinter
bg_img = tk.PhotoImage(file='bg_pic.png')

# Создаем текстовую/графическую метку (Label), куда передаем фоновую картинку
lbl_bg = tk.Label(window, image=bg_img)

# Растягиваем метку с картинкой на все окно:
# x=0, y=0 — начало в левом верхнем углу;
# relwidth=1, relheight=1 — ширина и высота равны 100% от размера окна (растягивание)
lbl_bg.place(x=0, y=0, relwidth=1, relheight=1)

# Создаем Frame (контейнер/рамку), внутри которого сгруппируем остальные элементы интерфейса
frame = tk.Frame(window)

# Размещаем контейнер ровно по центру окна:
# relx=0.5, rely=0.5 — центр окна (50% по горизонтали и вертикали),
# anchor='center' — точка привязки самого контейнера тоже его геометрический центр
frame.place(relx=0.5, rely=0.5, anchor='center')

# --- Блок для коэффициента A ---
# Создаем текстовую метку с буквой 'A':
# font=('Arial', 30) — шрифт Arial, размер 30
# bg='blue' — синий цвет фона метки, fg='white' — белый цвет текста
lbl_A = tk.Label(frame, text='A', font=('Arial', 30), bg='blue', fg='white')
# Размещаем метку в сетке: столбец 0, строка 0, с внутренними отступами padx=10 (по бокам) и pady=15 (сверху/снизу)
lbl_A.grid(column=0, row=0, padx=10, pady=15)

# Создаем поле для ввода текста (Entry) шириной в 10 символов
arg_A = tk.Entry(frame, width=10)
# Вставляем начальное значение '1' на позицию 0 (в начало поля)
arg_A.insert(0, '1')
# Размещаем поле ввода в сетке под меткой 'A': столбец 0, строка 1
arg_A.grid(column=0, row=1, padx=10, pady=15)

# --- Блок для коэффициента B ---
# Текстовая метка с буквой 'B'
lbl_B = tk.Label(frame, text='B', font=('Arial', 30))
# Размещаем метку в столбце 1, строке 0
lbl_B.grid(column=1, row=0, padx=10, pady=15)

# Поле для ввода коэффициента B
arg_B = tk.Entry(frame, width=10)
# Вставляем начальное значение '0'
arg_B.insert(0, '0')
# Размещаем поле ввода в столбце 1, строке 1
arg_B.grid(column=1, row=1, padx=10, pady=15)

# --- Блок для коэффициента C ---
# Текстовая метка с буквой 'C'
lbl_C = tk.Label(frame, text='C', font=('Arial', 30))
# Размещаем метку в столбце 2, строке 0
lbl_C.grid(column=2, row=0, padx=10, pady=15)

# Поле для ввода коэффициента C
arg_C = tk.Entry(frame, width=10)
# Вставляем начальное значение '0'
arg_C.insert(0, '0')
# Размещаем поле ввода в столбце 2, строке 1
arg_C.grid(column=2, row=1, padx=10, pady=15)

# --- Блок вывода результата ---
# Метка с постоянной надписью 'Result:'
