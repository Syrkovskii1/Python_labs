# Размещаем в столбце 1, строке 2 (по центру под полями ввода)
lbl_roots.grid(column=1, row=2)

# Метка, в которую будет выводиться сам результат (изначально текст 'None yet.')
lbl_result = tk.Label(frame, text='None yet.', font=('Arial', 10))
# Размещаем в столбце 2, строке 2 (правее слова 'Result:')
lbl_result.grid(column=2, row=2)

# --- Кнопки управления ---
# Кнопка 'Calculate':
# text='Calculate' — текст на кнопке,
# command=calc — указывает, какую функцию вызывать при клике (функция calc)
